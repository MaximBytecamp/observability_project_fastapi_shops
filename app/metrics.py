"""Все метрики сервиса заказов в одном месте.

Почему отдельный файл: так сразу видно, что именно сервис отдаёт на /metrics,
и метрику нельзя случайно объявить второй раз в другом модуле.

Почему собственный CollectorRegistry, а не глобальный реестр библиотеки:
в глобальном реестре по умолчанию лежат метрики интерпретатора и процесса
(python_gc_*, process_*). Нам нужен ответ, в котором есть только наши семь
метрик, чтобы было видно, откуда берётся каждая строка.

Правило для меток (labels), общее для всего файла:
каждое новое сочетание значений меток — это отдельный временной ряд в Prometheus.
Поэтому в метки пишем только значения из короткого заранее известного списка:
метод, шаблон маршрута, код ответа, напиток, результат, причина отказа.
Номер заказа, имя клиента, request_id, конкретный адрес /orders/123 в метки НЕ пишем:
у них нет верхней границы, и каждый новый заказ создавал бы новые ряды
(рост кардинальности → рост памяти Prometheus и медленные запросы).
Такие данные место в логах, а не в метриках.
"""

from prometheus_client import (
    CollectorRegistry,
    Counter,
    Gauge,
    Histogram,
    disable_created_metrics,
)

# Без этого вызова у каждого ряда счётчика и гистограммы появится парный ряд
# *_created со временем создания ряда. Для учебного стенда он только удваивает
# число строк на /metrics.
disable_created_metrics()

registry = CollectorRegistry()

# ---------------------------------------------------------------- HTTP

# counter: число запросов только растёт; скорость считаем в PromQL через rate().
# route — ШАБЛОН маршрута ("/orders/{order_id}"), а не адрес запроса.
# status — код ответа строкой ("202", "503"). Значений немного: 2xx/4xx/5xx из API.
HTTP_REQUESTS = Counter(
    "coffee_http_requests_total",
    "HTTP-запросы к API кофейни (без /metrics и /health)",
    ["method", "route", "status"],
    registry=registry,
)

# histogram: нужна не средняя, а распределение длительности, чтобы считать p95.
# Границы корзин: API отвечает из памяти, типичный ответ — единицы миллисекунд.
# Начинаем с 5 мс (быстрее различать незачем) и заканчиваем 1 с: ответ дольше
# секунды для такого API — уже авария, точная цифра там не важна, такие
# запросы попадут в корзину +Inf.
HTTP_REQUEST_DURATION = Histogram(
    "coffee_http_request_duration_seconds",
    "Длительность обработки HTTP-запроса",
    ["route"],
    buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0),
    registry=registry,
)

# ---------------------------------------------------------------- Заказы

# counter: завершённые заказы. result — только "ready" или "failed".
# drink — один из пяти напитков меню. Итого не больше 5 × 2 = 10 рядов.
ORDERS = Counter(
    "coffee_orders_total",
    "Завершённые заказы по напитку и результату",
    ["drink", "result"],
    registry=registry,
)

# histogram: время приготовления. Самый быстрый напиток — espresso ~1 с
# (с разбросом −30 % это 0,7 с), самый долгий — raf ~4 с (до 5,2 с),
# а в SLOW_MODE всё умножается на 3 (raf до ~15,6 с).
# Поэтому корзины от 0,5 с до 15 с, чаще там, где лежит большинство заказов (1–6 с).
ORDER_PREPARE = Histogram(
    "coffee_order_prepare_seconds",
    "Время приготовления готового заказа",
    ["drink"],
    buckets=(0.5, 1, 1.5, 2, 3, 4, 5, 6, 8, 10, 12, 15),
    registry=registry,
)

# gauge: значение и растёт, и падает — это состояние «прямо сейчас».
# Меток нет, поэтому ряд существует с момента запуска и равен 0.
QUEUE_LENGTH = Gauge(
    "coffee_queue_length",
    "Заказов в очереди сейчас (ещё не взяты бариста)",
    registry=registry,
)

BARISTAS_BUSY = Gauge(
    "coffee_baristas_busy",
    "Сколько бариста (фоновых обработчиков) сейчас готовят",
    registry=registry,
)

# counter: отклонённые заказы. reason — "queue_full" (503) или "invalid" (422).
ORDERS_REJECTED = Counter(
    "coffee_orders_rejected_total",
    "Отклонённые заказы по причине",
    ["reason"],
    registry=registry,
)
